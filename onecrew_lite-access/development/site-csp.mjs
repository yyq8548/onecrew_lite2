import { createHash } from "node:crypto";
import { readdir, readFile } from "node:fs/promises";
import { relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

import { parse } from "parse5";

const JAVASCRIPT_MIME_TYPES = new Set([
  "application/ecmascript",
  "application/javascript",
  "application/x-ecmascript",
  "application/x-javascript",
  "text/ecmascript",
  "text/javascript",
  "text/javascript1.0",
  "text/javascript1.1",
  "text/javascript1.2",
  "text/javascript1.3",
  "text/javascript1.4",
  "text/javascript1.5",
  "text/jscript",
  "text/livescript",
  "text/x-ecmascript",
  "text/x-javascript",
]);

const MIME_TYPE = /^[!#$%&'*+.^_`|~0-9A-Za-z-]+\/[!#$%&'*+.^_`|~0-9A-Za-z-]+(?:\s*;.*)?$/;

function attribute(node, name) {
  return node.attrs?.find((candidate) => candidate.name.toLowerCase() === name);
}

function scriptKind(node, source) {
  if (attribute(node, "src")) return "external";
  const typeAttribute = attribute(node, "type");
  if (!typeAttribute) return "executable";

  const type = typeAttribute.value.trim().toLowerCase();
  if (!type) throw new Error(`${source}: inline script has an empty type attribute`);
  if (type === "module") return "executable";
  if (MIME_TYPE.test(type)) {
    const essence = type.split(";", 1)[0].trim();
    return JAVASCRIPT_MIME_TYPES.has(essence) ? "executable" : "data";
  }
  throw new Error(`${source}: inline script has an unknown type ${JSON.stringify(typeAttribute.value)}`);
}

function inlineSource(html, node, source) {
  const location = node.sourceCodeLocation;
  if (!location?.startTag || !location.endTag) {
    throw new Error(`${source}: executable inline script does not have exact source offsets`);
  }
  const text = html.slice(location.startTag.endOffset, location.endTag.startOffset);
  if (!text) throw new Error(`${source}: executable inline script is empty`);
  return text;
}

export function analyzeSiteHtml(html, source = "HTML") {
  const document = parse(html, { sourceCodeLocationInfo: true });
  const hashes = new Set();
  const stack = [...document.childNodes];

  while (stack.length > 0) {
    const node = stack.pop();
    if (!node) continue;
    if (attribute(node, "style")) {
      throw new Error(`${source}: inline style attribute is forbidden`);
    }
    if (node.tagName === "style") {
      throw new Error(`${source}: inline style element is forbidden`);
    }
    if (node.tagName === "script" && scriptKind(node, source) === "executable") {
      const text = inlineSource(html, node, source);
      hashes.add(`'sha256-${createHash("sha256").update(text, "utf8").digest("base64")}'`);
    }
    if (node.childNodes) stack.push(...node.childNodes);
    if (node.content?.childNodes) stack.push(...node.content.childNodes);
  }

  return [...hashes].sort();
}

export function localizedSitePaths(pages) {
  return pages.flatMap(({ path }) => [
    path === "/" ? "/zh" : `/zh${path}`,
    path,
  ]).sort();
}

export function artifactForPath(pathname) {
  return pathname === "/" ? "index.html" : `${pathname.slice(1)}/index.html`;
}

async function htmlFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(entries.map(async (entry) => {
    const path = new URL(`${entry.name}${entry.isDirectory() ? "/" : ""}`, directory);
    if (entry.isDirectory()) return htmlFiles(path);
    return entry.isFile() && entry.name.endsWith(".html") ? [path] : [];
  }));
  return nested.flat();
}

export async function computeSiteCspManifest({ clientDirectory, pages }) {
  const paths = localizedSitePaths(pages);
  if (paths.length !== 48 || new Set(paths).size !== 48) {
    throw new Error("Site CSP generation requires exactly 48 unique localized paths");
  }

  const expectedArtifacts = new Map(paths.map((pathname) => [artifactForPath(pathname), pathname]));
  const discovered = await htmlFiles(clientDirectory);
  const discoveredArtifacts = new Set(discovered.map((url) => relative(
    fileURLToPath(clientDirectory),
    fileURLToPath(url),
  ).split(sep).join("/")));
  for (const artifact of expectedArtifacts.keys()) {
    if (!discoveredArtifacts.has(artifact)) throw new Error(`Site CSP path is missing ${artifact}`);
  }

  const manifest = {};
  for (const pathname of paths) {
    const artifact = artifactForPath(pathname);
    const html = await readFile(new URL(artifact, clientDirectory), "utf8");
    const hashes = analyzeSiteHtml(html, artifact);
    if (hashes.length === 0) throw new Error(`${artifact}: executable script hash list is empty`);
    manifest[pathname] = hashes;
  }
  return manifest;
}

export function manifestJson(manifest) {
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

export function manifestTypescript(manifest) {
  return [
    "// Generated by development/generate-site-csp.mjs. Do not edit.",
    `export const SITE_CSP_HASHES = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<string, readonly string[]>;`,
    "",
  ].join("\n");
}

export function verifySiteCspManifest(manifest, actualJson, actualTypescript) {
  if (actualJson !== manifestJson(manifest)) {
    throw new Error("Site CSP JSON manifest is stale or malformed");
  }
  if (actualTypescript !== manifestTypescript(manifest)) {
    throw new Error("Site CSP TypeScript manifest is stale or malformed");
  }
}
