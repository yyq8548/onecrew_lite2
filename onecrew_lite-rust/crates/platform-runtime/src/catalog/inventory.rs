//! Static capability declarations. Each declaration produces both its typed
//! identity and its inventory entry; consumers never maintain a second ID list.

use super::models::{CatalogSurface, OperationId, OperationSummary, ToolkitId, ToolkitSummary};

macro_rules! declare_operations {
    ($($name:ident => {
        id: $id:literal,
        toolkit: $toolkit:ident,
        title: $title:literal,
        summary: $summary:literal,
        surfaces: [$($surface:ident),+ $(,)?],
    }),+ $(,)?) => {
        impl OperationId {
            $(pub const $name: Self = Self::from_static($id);)+
        }

        pub(super) static OPERATIONS: &[OperationSummary] = &[
            $(OperationSummary {
                id: OperationId::$name,
                toolkit_id: ToolkitId::$toolkit,
                title: $title,
                summary: $summary,
                surfaces: &[$(CatalogSurface::$surface),+],
            }),+
        ];
    };
}

