import assert from "node:assert/strict";
import { mkdtemp } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { join } from "node:path";
import { backup, DatabaseSync } from "node:sqlite";
import { test } from "node:test";
import { z } from "zod";
import { DiscoveryRepository } from "../src/discovery/repository.ts";
import { buildDiscoveryMatchPrompt, buildDiscoveryScoreRequest, discoveryMatchPromptMaterial, discoveryRequiredCountFindings, loadBundledDiscoveryMatchRubric } from "../src/discovery/semantic-match.ts";
import { applyDiscoveryRequirements } from "../src/discovery/review-requirements.ts";
import { applyDiscoverySelectionQuality } from "../src/discovery/selection-quality.ts";

test("真实 Instagram 网页回执接入补读，保留全部结果与读取次数，并复用原身份和观察时间", { skip: !process.env.ONECREW_INSTAGRAM_REGRESSION_DATABASE }, async () => {
  const root = await mkdtemp(fileURLToPath(new URL("../../.scratch/instagram-web-content-", import.meta.url)));
  using source = new DatabaseSync(process.env.ONECREW_INSTAGRAM_REGRESSION_DATABASE!, { readOnly: true });
  const path = join(root, "creator.sqlite"); await backup(source, path);
  using db = new DatabaseSync(path); db.exec("PRAGMA foreign_keys=ON");
  const campaign = "02b4bf21-c7c0-4ee1-8724-4047323d66cb", repo = new DiscoveryRepository(db);
  const candidates = () => db.prepare("SELECT * FROM discovery_candidates WHERE discovery_campaign_id=? ORDER BY id").all(campaign);
  const before = candidates(), used = repo.getPlan(campaign).used_calls;
  const hit = repo.nextContentHit(campaign, "instagram");
  assert.ok(hit, "待补证的网页主页必须进入内容队列");
  assert.equal(repo.nextContentHit(campaign, "instagram"), hit);
  assert.deepEqual(candidates(), before);
  assert.equal(repo.getPlan(campaign).used_calls, used, "复用已存材料不能算成新读取");
  const snapshot = repo.prepareLibrarySnapshot(campaign, 1);
  assert.equal(new Set(snapshot.rows.map(row => row.hit.id)).size, snapshot.rows.length, "网页和补读共用一份主页时，结果表每条来源只能出现一次");
  const profile = repo.getProfile(campaign, hit), web = repo.getWebSource(campaign, hit);
  assert.equal(profile.claim.author_id, web.native_author_id);
  assert.equal(profile.claim.call_number, web.claim.call_number);
  assert.equal(profile.captured_at, web.captured_at);
  assert.deepEqual(profile.native_profile, z.record(z.string(), z.unknown()).parse(web.native_material).profile);
  const material = repo.prepareReviewMaterial(campaign, 1, hit), rubric = await loadBundledDiscoveryMatchRubric();
  const compact = buildDiscoveryScoreRequest(repo.getPlan(campaign).brief, material, material.native_followers ?? null, rubric);
  const legacy = buildDiscoveryMatchPrompt(repo.getPlan(campaign).brief, material, discoveryMatchPromptMaterial(material, material.native_followers ?? null), rubric);
  assert.ok(compact.scoringContext.length + compact.prompt.length < legacy.length * 0.8, "常规评估减少重复输入");
  assert.ok(compact.scoringContext.includes("95") && compact.scoringContext.includes("40") && compact.scoringContext.includes("OR"));
  console.log(JSON.stringify({ compact_bytes: Buffer.byteLength(compact.scoringContext + compact.prompt), previous_bytes: Buffer.byteLength(legacy) }));
  const below = db.prepare("SELECT search_hit_id FROM discovery_web_source_reads WHERE discovery_campaign_id=? AND status='completed' AND json_extract(native_material_json,'$.profile.follower_count')<2000 LIMIT 1").get(campaign);
  assert.ok(below);
  const low = repo.prepareReviewMaterial(campaign, 1, String(below.search_hit_id));
  const findings = discoveryRequiredCountFindings(low, low.native_followers ?? null, repo.getPlan(campaign).brief);
  assert.ok(findings, "有其他岗位或身份条件也不能把明确低粉账号送去模型");
  const selection = applyDiscoverySelectionQuality(low, findings, {}, "recorded-low-follower");
  applyDiscoveryRequirements(low, findings, selection, "recorded-low-follower", 1);
  assert.equal(z.record(z.string(), z.unknown()).parse(selection.reviewed_selection).outcome, "contradicted");
  assert.equal(z.record(z.string(), z.unknown()).parse(selection.reviewed_quality).outcome, "insufficient");
  const claim = repo.claimContent(campaign, 1, hit);
  assert.equal(claim.call_number, Number(used) + 1);
  assert.equal(claim.author_id, web.native_author_id);
  assert.equal(claim.source_url, profile.claim.author_url);
  assert.equal(repo.nextContentHit(campaign, "instagram"), null, "同一平台已有领取，不能重复读取");
  assert.deepEqual(candidates(), before);
});
