import assert from "node:assert/strict";
import { test } from "node:test";
import { mkdtemp } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { DatabaseSync } from "node:sqlite";
import { initializeNewCreatorDatabase } from "../src/storage/creator-schema.ts";
import { createPrivateDirectory } from "../src/storage/private-backup.ts";
import { GmailBulkRepository } from "../src/mail/gmail-bulk-repository.ts";
import { GmailReplyRepository } from "../src/mail/gmail-reply-repository.ts";
import { compileGmailBulkMessage, messageForGmailBulkClaim, verifyGmailBulkReadback } from "../src/mail/gmail-mime.ts";
import { bulkIdempotencyKey } from "../src/mail/gmail-bulk.ts";

test("真实schema90原发送历史和晚到回执原子提交，永久标记禁止重新发送", async () => {
  const directory = await mkdtemp(fileURLToPath(new URL("../../.scratch/gmail-send-history-", import.meta.url)));
  const path = join(await createPrivateDirectory(join(directory, "private")), "creator.sqlite");
  await initializeNewCreatorDatabase(path);
  const db = new DatabaseSync(path);
  try {
    db.exec("PRAGMA journal_mode=WAL; PRAGMA synchronous=FULL; PRAGMA foreign_keys=ON");
    db.prepare("INSERT INTO mailbox_refs VALUES ('box','gmail','Gmail','sender@example.com',NULL,'[\"send\",\"inbox\",\"sent_readback\"]',1,NULL,1,1)").run();
    const repo = new GmailBulkRepository(db);
    const batch = repo.create({ mailbox_ref_id: "box", subject: "你好", body: "真实本地编译正文", recipients: [{ email: "recipient@example.com", source: "Creator email" }] });
    repo.control(batch.id, "confirm");
    const claim = repo.claim()!;
    const message = messageForGmailBulkClaim(claim.batch, claim.item, "sender@example.com");
    assert.equal(repo.reserveSendAttempt(batch.id, claim.item, message), true);
    assert.equal(repo.reserveSendAttempt(batch.id, claim.item, message), false);
    const key = bulkIdempotencyKey(claim.item);
    const started = db.prepare("SELECT state,result_json FROM idempotency_records WHERE key=?").get(key)!;
    assert.equal(started.state, "remote_started");
    assert.equal(JSON.parse(String(started.result_json)).provider_thread_key, `manual:box:recipient@example.com:send:${key}`);
    const compiled = await compileGmailBulkMessage(message);
    const receipt = await verifyGmailBulkReadback({ id: "abcd", internalDate: "1791786972000", raw: compiled.raw, labelIds: ["SENT"] }, "abcd", message);
    repo.interrupt();
    assert.equal(repo.get(batch.id).items[0]!.state, "unknown");
    assert.throws(() => repo.reconcileReceipt(batch.id, { ...claim.item, state: "sent", provider_message_id: "abcd" }, key, false, { ...receipt, subject: "篡改" }));
    assert.equal(db.prepare("SELECT COUNT(*) AS n FROM email_threads").get()!.n, 0);
    repo.recordProviderAcceptance(batch.id, claim.item, "abcd");
    assert.equal(db.prepare("SELECT state FROM idempotency_records WHERE key=?").get(key)!.state, "remote_accepted");
    repo.stageVerifiedReceipt(batch.id, claim.item, receipt);
    assert.equal(db.prepare("SELECT state FROM idempotency_records WHERE key=?").get(key)!.state, "remote_verified");
    assert.equal(db.prepare("SELECT COUNT(*) AS n FROM email_threads").get()!.n, 0);
    const staged = String(db.prepare("SELECT result_json FROM idempotency_records WHERE key=?").get(key)!.result_json);
    db.prepare("UPDATE idempotency_records SET result_json=? WHERE key=?").run(JSON.stringify({ ...JSON.parse(staged), verified_provider_message_id: "ffff" }), key);
    assert.throws(() => repo.recoverVerifiedReceipts(), /context_mismatch/);
    assert.equal(db.prepare("SELECT COUNT(*) AS n FROM audit_events").get()!.n, 0);
    db.prepare("UPDATE idempotency_records SET result_json=? WHERE key=?").run(staged, key);
    assert.equal(repo.recoverVerifiedReceipts(), 1);
    assert.equal(repo.recoverVerifiedReceipts(), 0);
    assert.equal(repo.get(batch.id).items[0]!.state, "sent");
    assert.equal(db.prepare("SELECT state FROM idempotency_records WHERE key=?").get(key)!.state, "completed");
    assert.equal(db.prepare("SELECT origin FROM emails WHERE provider_message_id='abcd'").get()!.origin, "confirmed_send");
    assert.equal(db.prepare("SELECT COUNT(*) AS n FROM email_recipients").get()!.n, 2);
    assert.equal(db.prepare("SELECT COUNT(*) AS n FROM audit_events WHERE kind='manual_email_sent'").get()!.n, 1);
    assert.equal(db.prepare("SELECT detail_complete FROM email_provider_identities WHERE provider_message_id='abcd'").get()!.detail_complete, 1);
    const replies = new GmailReplyRepository(db, { accountId: "user", tenantId: "tenant", baseId: "base" });
    assert.equal(replies.seeds("box")[0]!.providerMessageId, "abcd");
    const duplicate = repo.create({ mailbox_ref_id: "box", subject: batch.subject, body: batch.body, recipients: [{ email: "recipient@example.com", source: "another source" }] });
    repo.control(duplicate.id, "confirm");
    assert.equal(repo.claim()!.item.state, "failed");
  } finally { db.close(); }
});
