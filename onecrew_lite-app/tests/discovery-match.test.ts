import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile } from "node:fs/promises";
import { test } from "node:test";
import { z } from "zod";
import { parseApplicationJson } from "../src/contracts/application-json.ts";
import { buildDiscoveryMatchPrompt, buildDiscoveryScoreRequest, discoveryMatchEvidenceKey, discoveryMatchPromptMaterial, loadBundledDiscoveryMatchRubric } from "../src/discovery/semantic-match.ts";
import type { DiscoveryReviewMaterial } from "../src/discovery/review-material.ts";

test("真实旧评分材料使用GitHub新创作者规则，幂等键与旧规则回执隔离", async () => {
  const fixture = z.object({ count: z.number(), objective: z.string(), material: z.record(z.string(), z.unknown()), prompt_sha256: z.string(), request_id: z.string(), reassess_request_id: z.string() }).parse(parseApplicationJson(await readFile(new URL("./fixtures/discovery-match-rust.json", import.meta.url))));
  const material = fixture.material as DiscoveryReviewMaterial, rubric = await loadBundledDiscoveryMatchRubric();
  const automatic = discoveryMatchEvidenceKey(material, fixture.count, rubric, false);
  const reassess = discoveryMatchEvidenceKey(material, fixture.count, rubric, true);
  assert.notEqual(automatic, fixture.request_id);
  assert.notEqual(reassess, fixture.reassess_request_id);
  assert.notEqual(automatic, reassess);
  assert.equal(discoveryMatchEvidenceKey(material, fixture.count, rubric, false), automatic);
  assert.equal(createHash("sha256").update(rubric).digest("hex"), "7e8a0a14761c9ea86f5e9083dc68daa82cf9b504b86d39433ad7150cf2d2ae81");
  const projection = discoveryMatchPromptMaterial(material, fixture.count);
  assert.equal(projection.language_samples, null);
  const prompt = buildDiscoveryMatchPrompt(fixture.objective, material, projection, rubric);
  assert.notEqual(createHash("sha256").update(prompt).digest("hex"), fixture.prompt_sha256);
  assert.ok(prompt.includes("Relevant reposts, curated compilations, reactions and topic hashtags"));
  assert.ok(prompt.includes("Original creation is NOT required unless the approved criteria explicitly require it"));
  assert.ok(prompt.includes("distinguish an observed content hashtag from the search query itself"));
  assert.ok(prompt.includes("score immediately"));
  assert.ok(prompt.includes("specific product/category hashtags actually observed"));
  const compact = JSON.parse(prompt.split("UNTRUSTED_SAVED_DATA:\n")[1]!).material;
  assert.equal(compact.campaign_id, undefined);
  assert.deepEqual(compact.native_profile, projection.native_profile);
  assert.equal(compact.video_description, projection.video_description);
  assert.equal(compact.transcript?.call_number, undefined);
  assert.deepEqual(compact.transcript?.segments, material.transcript?.segments);
  const request = buildDiscoveryScoreRequest(fixture.objective, material, fixture.count, rubric);
  assert.ok(request.scoringContext.includes("requirements[index]"));
  assert.ok(request.scoringContext.includes("quality.score is 95/85/70/40"));
  assert.ok(!request.scoringContext.includes("criterion="));
  assert.ok(!request.scoringContext.includes("match_level"));
  assert.ok(!request.scoringContext.includes("requirement_findings"));
  assert.ok(!request.scoringContext.includes("Ignore older output-format"));
  assert.ok(request.scoringContext.includes("Preserve nested groups and exclusions"));
  assert.equal(discoveryMatchEvidenceKey(material, fixture.count, rubric, false), automatic);
});
