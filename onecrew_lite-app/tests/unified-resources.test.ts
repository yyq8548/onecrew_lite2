import assert from "node:assert/strict";
import { mkdir, mkdtemp, rm } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import test from "node:test";
import { load } from "cheerio";
import { unifiedResources } from "../src/application/unified-resources.ts";
import { retiredOperations } from "../src/contracts/retired-operations.ts";
import { startLocalRuntime } from "../src/service/runtime.ts";
import { createPrivateDirectory } from "../src/storage/private-backup.ts";
import { parse as parseCookie } from "hono/utils/cookie";
import { browserCookieName } from "../src/service/browser-sessions.ts";
import { localServiceStatus } from "@onecrew/runtime-contracts/status";

test("unified service starts and closes real embedded PGlite behind the same authenticated listener", async () => {
  const scratch = fileURLToPath(new URL("../../.scratch/unified-resources-tests/", import.meta.url));
  await mkdir(scratch, { recursive: true });
  const root = await mkdtemp(join(scratch, "service-"));
  const directory = await createPrivateDirectory(join(root, "private"));
  let runtime: Awaited<ReturnType<typeof startLocalRuntime>> | undefined;
  try {
    runtime = await startLocalRuntime(directory, unifiedResources({ vaultPath: join(directory, "vault.sqlite"), masterKeyPath: join(directory, "master.key"), webAssetsDirectory: fileURLToPath(new URL("../../onecrew_lite-web/dist", import.meta.url)), libraryWebAssetsDirectory: fileURLToPath(new URL("../../onecrew_lite-library/web/dist", import.meta.url)) }));
    const status = await fetch(`${runtime.descriptor.url}/_local/status`, { headers: { authorization: `Bearer ${runtime.descriptor.control_token}` } });
    assert.equal(status.status, 200);
    const body = await status.json();
    assert.equal(body.production_ready, false);
    assert.ok(body.registered_operations.includes("onecrew_gmail_bulk_prepare"));
    assert.ok(body.registered_operations.includes("onecrew_creator_manual_create"));
    for (const operation of retiredOperations) assert.ok(!body.registered_operations.includes(operation));
    const page = await fetch(runtime.descriptor.url);
    assert.equal(page.status, 200);
    assert.match(page.headers.get("content-type")!, /text\/html/);
    const html = await page.text();
    const asset = load(html)("script[src]").first().attr("src");
    assert.ok(asset);
    assert.equal((await fetch(new URL(asset, runtime.descriptor.url))).status, 200);
    assert.equal((await fetch(runtime.descriptor.url, { headers: { origin: "https://hostile.example" } })).status, 403);
    assert.equal((await fetch(`${runtime.descriptor.url}/api/v1/dynamic-tables`)).status, 401);
    const accessHeaders = { authorization: `Bearer ${runtime.descriptor.control_token}` };
    const libraryStatus = await fetch(`${runtime.descriptor.url}/_local/library/status`, { headers: accessHeaders });
    const libraryIdentity = await libraryStatus.json();
    assert.equal(libraryIdentity.ready, true);
    assert.match(libraryIdentity.web_assets_sha256, /^[a-f0-9]{64}$/);
    const libraryPage = await fetch(`${runtime.descriptor.url}/library`);
    assert.equal(libraryPage.status, 200);
    const libraryAsset = load(await libraryPage.text())('script[src]').first().attr('src');
    assert.ok(libraryAsset);
    assert.ok(libraryAsset?.startsWith('/library/assets/'));
    assert.equal((await fetch(new URL(libraryAsset, runtime.descriptor.url))).status, 200);
    assert.equal((await fetch(`${runtime.descriptor.url}/library`, { method: 'HEAD' })).status, 200);
    assert.equal((await fetch(`${runtime.descriptor.url}/library`, { headers: { origin: 'https://hostile.example' } })).status, 403);
    assert.equal((await fetch(`${runtime.descriptor.url}/_local/library/status`)).status, 401);
    assert.deepEqual(await (await fetch(`${runtime.descriptor.url}/_local/mail/worker`, { headers: accessHeaders })).json(), { running: false, failed: false });
    assert.equal((await fetch(`${runtime.descriptor.url}/_local/access/status`)).status, 401);
    const accessStatus = await fetch(`${runtime.descriptor.url}/_local/access/status`, { headers: accessHeaders });
    assert.equal(accessStatus.status, 200);
    assert.equal((await accessStatus.json()).state, "signed_out");
    const initialShell = await fetch(`${runtime.descriptor.url}/_local/service/status`, { headers: accessHeaders });
    assert.equal(initialShell.status, 200);
    const initialLogin = localServiceStatus.parse(await initialShell.json()).login!;
    assert.equal(initialLogin.status.issue, null);
    assert.equal(initialLogin.status.state, "pairing_required");
    const pairing = await fetch(`${runtime.descriptor.url}/_local/access/login`, { method: "POST", headers: accessHeaders });
    assert.equal(pairing.status, 200);
    const pairingResult = await pairing.json();
    const authorize = new URL(pairingResult.authorizeUrl);
    assert.equal(authorize.origin, "https://access.onecrewai.io");
    assert.equal(authorize.pathname, "/pairing/authorize");
    assert.equal(authorize.searchParams.get("app_version"), "0.9.1");
    assert.equal(authorize.searchParams.get("code_challenge_method"), "S256");
    assert.equal((await (await fetch(`${runtime.descriptor.url}/_local/access/status`, { headers: accessHeaders })).json()).flowId, pairingResult.flowId);
    const cancelled = await fetch(`${runtime.descriptor.url}/_local/access/cancel`, { method: "POST", headers: accessHeaders });
    assert.equal(cancelled.status, 200);
    assert.equal((await cancelled.json()).state, "signed_out");
    assert.equal((await fetch(`${runtime.descriptor.url}/_local/workspace`, { method: "POST" })).status, 401);
    const workspace = await fetch(`${runtime.descriptor.url}/_local/workspace`, { method: "POST", headers: accessHeaders });
    assert.equal(workspace.status, 200);
    const workspaceUrl = new URL((await workspace.json()).url);
    const ticket = new URLSearchParams(workspaceUrl.hash.slice(1)).get('onecrew_ticket');
    assert.ok(ticket);
    const exchange = () => fetch(`${runtime!.descriptor.url}/api/local/session`, { method: 'POST', headers: { origin: workspaceUrl.origin, 'Content-Type': 'application/json' }, body: JSON.stringify({ ticket }) });
    const sessionResponse = await exchange();
    assert.equal(sessionResponse.status, 200);
    const session = await sessionResponse.json();
    assert.equal(session.scope, 'bootstrap');
    assert.equal(session.accountId, undefined);
    const name = browserCookieName(workspaceUrl.origin);
    const cookies = parseCookie(sessionResponse.headers.getSetCookie().join('; '));
    const cookie = `${name}=${cookies[name]}`;
    assert.equal((await exchange()).status, 401);
    const command = (name: string, input: unknown = {}, csrf = session.csrf) => fetch(`${runtime!.descriptor.url}/api/commands/${name}`, { method: 'POST', headers: { cookie, origin: workspaceUrl.origin, 'Content-Type': 'application/json', ...(csrf ? { 'X-OneCrew-CSRF': csrf } : {}) }, body: JSON.stringify(input) });
    assert.equal((await command('service_status', {}, '')).status, 401);
    const shell = await command('service_status');
    assert.equal(shell.status, 200);
    assert.equal(localServiceStatus.parse((await shell.json()).result).login!.status.state, 'pairing_required');
    assert.equal((await command('onecrew_gmail_bulk_prepare', { input: {} })).status, 403);
    assert.equal((await fetch(`${runtime.descriptor.url}/api/v1/dynamic-tables`, { headers: { cookie } })).status, 403);
    assert.equal((await fetch(`${runtime.descriptor.url}/_local/status`, { headers: { cookie } })).status, 401);
    const started = await command('creator_sync_pairing_begin');
    assert.equal(started.status, 200);
    const browserPairing = (await started.json()).result;
    assert.equal(browserPairing.projection.status.state, 'pairing_pending');
    const reopened = await command('creator_sync_pairing_reopen');
    assert.equal(reopened.status, 200);
    assert.equal((await reopened.json()).result.authorize_url, browserPairing.authorize_url);
    const unchanged = await fetch(`${runtime.descriptor.url}/api/session`, { headers: { cookie } });
    assert.equal((await unchanged.json()).result.protocol_version, 1);
    assert.equal((await command('creator_sync_pairing_cancel')).status, 200);
    await runtime.close();
    await runtime.stopped;
    runtime = undefined;
  } finally {
    if (runtime) await runtime.close();
    await rm(root, { recursive: true });
  }
});
