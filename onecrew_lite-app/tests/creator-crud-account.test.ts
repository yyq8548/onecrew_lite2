import assert from "node:assert/strict";
import { mkdtemp } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { test } from "node:test";
import { OperationRegistry } from "../src/application/operation-registry.ts";
import { registerCreatorOperations } from "../src/creators/operations.ts";
import { AccountDatabases } from "../src/identity/account-databases.ts";
import { AccountContextService } from "../src/identity/account-context.ts";
import { acquireInstanceLock } from "../src/service/instance-lock.ts";
import { createPrivateDirectory } from "../src/storage/private-backup.ts";

test("真实账号数据库解析隔离Creator，成功提交才发出当前账号失效通知", async () => {
  const directory = await mkdtemp(fileURLToPath(new URL("../../.scratch/creator-crud-account-", import.meta.url)));
  const lease = await acquireInstanceLock(await createPrivateDirectory(join(directory, "private")));
  const accounts = new AccountContextService();
  const databases = new AccountDatabases(lease, accounts);
  try {
    const a = { user: { id: "creator-a", email: "a@example.com" }, tenantId: "tenant-a", baseId: "base-a", deviceId: "device", source: "access" as const };
    const b = { user: { id: "creator-b", email: "b@example.com" }, tenantId: "tenant-b", baseId: "base-b", deviceId: "device", source: "access" as const };
    await databases.createNewAccount(accounts.activate(a));
    await databases.createNewAccount(accounts.activate(b));
    const first = accounts.activate(a);
    const registry = new OperationRegistry(accounts);
    const changes: { account: string; scopes: readonly string[] }[] = [];
    registerCreatorOperations(registry, databases.creatorsResolver(), accounts, (context, scopes) => changes.push({ account: context.principal.user.id, scopes }));
    const created = await registry.execute("onecrew_creator_manual_create", { input: { display_name: "Account A" } }, a.user.id, first.epoch) as { creator_id: string };
    assert.deepEqual(changes, [{ account: a.user.id, scopes: ["creators"] }]);
    await assert.rejects(registry.execute("onecrew_creator_update", { input: { creator_id: created.creator_id, score: 101 } }, a.user.id, first.epoch));
    assert.equal(changes.length, 1);
    const second = accounts.activate(b);
    await assert.rejects(registry.execute("onecrew_creator_get", { input: { creator_id: created.creator_id } }, a.user.id, first.epoch), { code: "access.account_changed" });
    await assert.rejects(registry.execute("onecrew_creator_get", { input: { creator_id: created.creator_id } }, b.user.id, second.epoch), /creator not found/u);
    const page = await registry.execute("onecrew_creator_list", { input: {} }, b.user.id, second.epoch) as { items: unknown[] };
    assert.deepEqual(page.items, []);
    assert.equal(changes.length, 1);
    const again = accounts.activate(a);
    await registry.execute("onecrew_creator_update", { input: { creator_id: created.creator_id, notes: "updated" } }, a.user.id, again.epoch);
    await registry.execute("onecrew_creator_delete", { input: { creator_id: created.creator_id } }, a.user.id, again.epoch);
    assert.equal(changes.length, 3);
    assert.ok(changes.every(change => change.account === a.user.id));
    await assert.rejects(registry.execute("onecrew_creator_delete", { input: { creator_id: created.creator_id } }, a.user.id, again.epoch));
    assert.equal(changes.length, 3);
    changes.length = 0;
    const invoke = (name: string, input: unknown) => registry.execute(name, input, a.user.id, again.epoch);
    const group = await invoke("onecrew_creator_group_create", { input: { name: "Launch" } }) as { id: string; revision: number };
    const member = await invoke("onecrew_creator_manual_create", { input: { display_name: "Grouped" } }) as { creator_id: string };
    const move = { input: { creator_id: member.creator_id, destination: { kind: "group", group_id: group.id } } };
    await invoke("onecrew_creator_group_set", move);
    await invoke("onecrew_creator_group_set", move);
    await invoke("onecrew_creator_group_update", { input: { group_id: group.id, expected_revision: 1, name: "Launch" } });
    assert.equal(changes.length, 3);
    await invoke("onecrew_creator_group_update", { input: { group_id: group.id, expected_revision: 1, name: "Renamed" } });
    await assert.rejects(invoke("onecrew_creator_group_update", { input: { group_id: group.id, expected_revision: 1, name: "Stale" } }));
    await invoke("onecrew_creator_group_list", { input: {} });
    await invoke("onecrew_creator_update_stage", { input: { creator_id: member.creator_id, stage: "engaged" } });
    await invoke("onecrew_creator_update_stage", { input: { creator_id: member.creator_id, stage: "engaged" } });
    await invoke("onecrew_creator_pin", { input: { creator_id: member.creator_id, pinned: true } });
    await invoke("onecrew_creator_archive", { creatorId: member.creator_id });
    await invoke("onecrew_creator_archive", { creatorId: member.creator_id });
    await invoke("onecrew_creator_group_delete", { input: { group_id: group.id, expected_revision: 2 } });
    assert.deepEqual(changes.map(change => change.scopes), [["creator_groups"], ["creators"], ["creator_groups", "creators"], ["creator_groups", "creators"], ["creators"], ["creators"], ["creators"], ["creator_groups", "creators"]]);
    assert.ok(changes.every(change => change.account === a.user.id));
    const surviving = await invoke("onecrew_creator_get", { input: { creator_id: member.creator_id } }) as { group: null; creator: { archived_at: number } };
    assert.equal(surviving.group, null);
    assert.ok(surviving.creator.archived_at);
  } finally { databases.close(); await lease.close(); }
});
